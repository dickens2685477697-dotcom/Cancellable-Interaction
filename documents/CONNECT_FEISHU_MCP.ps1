# Run locally in PowerShell. The personal MCP URL is entered without echo.
# Official setup: https://open.feishu.cn/page/mcp
# Create an MCP service, add Cloud Docs tools, authorize, then copy its server URL.
$ErrorActionPreference = 'Stop'
$codexCommand = Get-Command codex -ErrorAction SilentlyContinue
if (-not $codexCommand) {
    throw 'Codex CLI was not found in PATH. Run this script from a Codex terminal.'
}
$existing = & $codexCommand.Source mcp list --json
if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect current MCP configuration.' }
$servers = $existing | ConvertFrom-Json
if (@($servers | Where-Object { $_.name -eq 'feishu' }).Count -gt 0) {
    throw 'An MCP named feishu already exists. Inspect it in Codex Settings before replacing it.'
}
$secureUrl = Read-Host 'Paste your personal Feishu MCP server URL (hidden input)' -AsSecureString
$pointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secureUrl)
try {
    $serverUrl = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($pointer)
    $serverUri = $null
    if (-not [Uri]::TryCreate($serverUrl, [UriKind]::Absolute, [ref]$serverUri)) {
        throw 'Invalid MCP server URL.'
    }
    $officialHost = $serverUri.DnsSafeHost -match '(^|\.)(feishu\.cn|larkoffice\.com|larksuite\.com)$'
    if ($serverUri.Scheme -ne 'https' -or -not $officialHost -or $serverUri.UserInfo) {
        throw 'Expected an HTTPS URL generated by the official Feishu MCP platform.'
    }
    # Store through Codex CLI. Do not print the URL or full MCP configuration.
    & $codexCommand.Source mcp add feishu --url $serverUrl *> $null
    if ($LASTEXITCODE -ne 0) { throw 'MCP registration failed. Check Codex Settings locally.' }
    $configured = & $codexCommand.Source mcp list --json | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0 -or -not @($configured | Where-Object { $_.name -eq 'feishu' -and $_.enabled }).Count) {
        throw 'Could not verify the enabled MCP registration.'
    }
    Write-Host 'Feishu MCP registered. Reopen the Codex chat to load its tools.'
    Write-Host 'Registration does not verify document access; check it in the next chat.'
} finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($pointer)
    $serverUrl = $null
    $secureUrl = $null
}
